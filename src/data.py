from pathlib import Path
from dataclasses import dataclass, field
from src.node_representation import get_node_embeddings
from src.similarities import rank_similar, cluster_nodes

@dataclass
class Data:
    # node and edge types from the input data
    node_types: list[str] = field(default_factory=list)
    edge_types: list[tuple[str, str, str]] = field(default_factory=list)
    # all nodes and edges from the input data
    node_edge_dictionary: dict = field(default_factory=dict)
    # dictionary containing different graphs based on different node combinations
    graph_dictionary: dict = field(default_factory=dict)
    # node embeddings to be generated by MetaPath2Vec
    node_representations: dict = field(default_factory=dict)
    # dictionary of similarity scores among nodes from several node type combinations
    similarities: dict = field(default_factory=dict)
    # dictionary of dataframes with node clusters per node type
    clusters: dict = field(default_factory=dict)

    def get_node_embeddings(self, metapath: list[tuple[str, str, str]], m2v_settings: dict):
        self.node_representations = get_node_embeddings(
            graph=self.graph_dictionary["all"],
            metapath=metapath,
            metapath_sett=m2v_settings,
        )

    def get_similarities(self, node_combos: list[tuple[str, str]], out_dir: Path):
        # check that node representations have been generated
        if not self.node_representations:
            raise ValueError("Node embeddings need to be generated before similarity calculation...")

        for node_type_a, node_type_b in node_combos:
            self.similarities[(node_type_a, node_type_b)] = rank_similar(
                embeddings_a=self.node_representations["embeddings"][node_type_a],
                embeddings_b=self.node_representations["embeddings"][node_type_b],
                names_a=list(self.graph_dictionary["all"].node_encodings[node_type_a].keys()),
                names_b=list(self.graph_dictionary["all"].node_encodings[node_type_b].keys()),
            )

        # save the similarity dataframes
        for (a, b), df in self.similarities.items():
            df.to_csv(out_dir / f"table_similarity_{a}_{b}.tsv", sep="\t", index=False)

    def cluster_nodes_by_type(self, out_dir: Path):
        for my_type in self.graph_dictionary["all"].node_encodings.keys():
            self.clusters[my_type] = cluster_nodes(
                embeddings=self.node_representations["embeddings"][my_type],
                names_a=list(self.graph_dictionary["all"].node_encodings[my_type].keys()),
                norm=True
            )

        for my_type, my_df in self.clusters.items():
            my_df.to_csv(out_dir / f"table_clusters_{my_type}.tsv", sep="\t", index=False)
